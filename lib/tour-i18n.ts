const norm = (s: string) => s.replace(/\r\n/g, "\n").replace(/[ \t]+/g, " ").trim();
const CONTENT_NORM = new Map(Object.entries(CONTENT).map(([k, v]) => [norm(k), v]));

/** Admin-written tour text in the staff member's language; unknown text stays as stored. */
export function translateContent(text: string, lang: Lang): string {
  if (lang === "en" || !text) return text;
  return CONTENT_NORM.get(norm(text))?.[lang] ?? text;
}
